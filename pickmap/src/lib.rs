//! Fast, immutable string maps built at compile time.
//!
//! [`static_map!`] looks at a map's keys while your crate compiles and generates a lookup
//! made for exactly those keys: a perfect hash over a few chosen bytes for small maps, or
//! a PtHash table for large ones. The result is a plain `static`: no allocation, `no_std`,
//! and lookups that don't slow down on inputs that nearly match a key.
//!
//! ```
//! use pickmap::{StaticMap, static_map};
//!
//! #[derive(Debug, PartialEq)]
//! pub enum Method { Get, Post, Put, Delete }
//!
//! static_map! {
//!     /// HTTP methods we handle.
//!     pub METHODS: Method;
//!     "GET" => Method::Get,
//!     "POST" => Method::Post,
//!     "PUT" => Method::Put,
//!     "DELETE" => Method::Delete,
//! }
//!
//! assert_eq!(METHODS.get("POST"), Some(&Method::Post));
//! assert_eq!(METHODS.get("PATCH"), None);
//! assert_eq!(METHODS.iter().map(|(k, _)| k).collect::<Vec<_>>(), ["GET", "POST", "PUT", "DELETE"]);
//!
//! // Generic code works through the StaticMap trait.
//! fn count<M: StaticMap>(map: &M) -> usize {
//!     map.len()
//! }
//! assert_eq!(count(&METHODS), 4);
//! ```
//!
//! # Tokens inside a buffer
//!
//! When the key is a slice of a larger buffer (a lexer's source, a request being
//! parsed), `get_in(buf, range)` gives the same answer as `get(&buf[range])` but reads
//! the key with one wide load from `buf`, masked to its length, never leaving `buf`:
//!
//! ```
//! # use pickmap::static_map;
//! # #[derive(Debug, PartialEq)] pub enum Method { Get, Post }
//! # static_map! { pub METHODS: Method; "GET" => Method::Get, "POST" => Method::Post }
//! let request = b"POST /upload HTTP/1.1\r\nHost: example.com\r\n";
//! assert_eq!(METHODS.get_in(request, 0..4), Some(&Method::Post));
//! ```
//!
//! # Syntax
//!
//! ```text
//! static_map! { [attributes] [vis] NAME: ValueType; "key" => value, ... }
//! ```
//!
//! - Keys are string literals (escaped and raw strings work); duplicates are a compile
//!   error.
//! - Values are any expression valid in a `static` of `ValueType`, which must be `Sync`.
//!   Elided lifetimes such as `&[u8]` are fine.
//! - `///` docs and other attributes apply to the static; `#[cfg]` and `#[cfg_attr]`
//!   apply to everything the macro generates.
//! - `#[pickmap(workload = "general" | "keyword_scan" | "mostly_hits")]` is a performance
//!   hint that never changes results. See the
//!   [README](https://github.com/dahankzter/pickmap#workloads) before changing the
//!   default.
//!
//! Benchmarks, design notes and limits are in the
//! [repository](https://github.com/dahankzter/pickmap).
#![no_std]

mod iter;

pub use iter::Iter;
pub use pickmap_macros::static_map;

/// A map generated by `static_map!`. Generic code takes `&impl StaticMap<Value = V>`.
pub trait StaticMap: Sync + 'static {
    type Value: 'static;

    /// The value for `key`, if the map has it.
    fn get(&self, key: &str) -> Option<&'static Self::Value>;

    /// The value for the key at `buf[range]`: the same answer as `get(&buf[range])`, but
    /// faster when `buf` continues past the key, as in a lexer or parser looking up a
    /// token inside its input. The key is read with one wide load from `buf` and masked,
    /// never leaving `buf`.
    ///
    /// # Panics
    ///
    /// If `range` is out of bounds for `buf`, like indexing.
    fn get_in<B: AsRef<[u8]> + ?Sized>(&self, buf: &B, range: core::ops::Range<usize>) -> Option<&'static Self::Value> {
        core::str::from_utf8(&buf.as_ref()[range]).ok().and_then(|s| self.get(s))
    }

    fn contains_key(&self, key: &str) -> bool {
        self.get(key).is_some()
    }

    fn len(&self) -> usize;

    fn is_empty(&self) -> bool {
        self.len() == 0
    }

    /// All entries, in declaration order.
    fn iter(&self) -> Iter<Self::Value>;
}

/// Used by generated code; not public API.
#[doc(hidden)]
pub mod __private {
    pub use crate::iter::Iter;
    pub use pickmap_core::{hash::*, load::*, slot::*};
}
